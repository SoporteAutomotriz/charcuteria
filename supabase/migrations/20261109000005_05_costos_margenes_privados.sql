-- Migración 5: Tablas privadas de costos y márgenes (Fase 2)
-- Tablas: producto_costos, producto_margenes, paquete_margenes
-- Todas privadas: solo rol propietario puede leer/escribir.
-- No hay políticas para el rol anon en ninguna de estas tablas.
-- Diseño según sección 11: costos y márgenes siempre en tablas separadas y privadas.
-- Las columnas de costo y margen nunca existieron en tablas públicas; se crean
-- aquí desde cero como tablas privadas, igual que ya existe cotizaciones_costos.

-- 1. producto_costos — costo de compra por producto
create table if not exists public.producto_costos (
  id bigint generated by default as identity primary key,
  producto_id bigint references public.productos(id) on delete cascade,
  costo_unitario_compra numeric(12,2) not null default 0,
  creado_en timestamptz not null default now(),
  actualizado_en timestamptz not null default now(),
  unique (producto_id)
);

-- 2. producto_margenes — margen propio y precio fijo manual por producto
create table if not exists public.producto_margenes (
  id bigint generated by default as identity primary key,
  producto_id bigint references public.productos(id) on delete cascade,
  margen_propio_pct numeric(5,2) not null default 0 check (margen_propio_pct between 0 and 100),
  precio_fijo_manual numeric(12,2),
  creado_en timestamptz not null default now(),
  actualizado_en timestamptz not null default now(),
  unique (producto_id)
);

-- 3. paquete_margenes — margen propio y precio fijo manual por paquete
create table if not exists public.paquete_margenes (
  id bigint generated by default as identity primary key,
  paquete_id bigint references public.paquetes(id) on delete cascade,
  margen_propio_pct numeric(5,2) not null default 0 check (margen_propio_pct between 0 and 100),
  precio_fijo_manual numeric(12,2),
  creado_en timestamptz not null default now(),
  actualizado_en timestamptz not null default now(),
  unique (paquete_id)
);

-- Índices para búsquedas frecuentes
create index if not exists idx_producto_costos_producto on public.producto_costos(producto_id);
create index if not exists idx_producto_margenes_producto on public.producto_margenes(producto_id);
create index if not exists idx_paquete_margenes_paquete on public.paquete_margenes(paquete_id);

-- ============================================================
-- POLÍTICAS RLS — Tablas privadas de costos y márgenes
-- ============================================================

-- producto_costos: solo propietario
create policy "producto_costos: solo propietario"
  on public.producto_costos
  for all
  to authenticated
  using (
    exists (
      select 1 from public.usuarios_personal up
      where up.id = auth.uid() and up.rol = 'propietario'
    )
  );

-- producto_margenes: solo propietario
create policy "producto_margenes: solo propietario"
  on public.producto_margenes
  for all
  to authenticated
  using (
    exists (
      select 1 from public.usuarios_personal up
      where up.id = auth.uid() and up.rol = 'propietario'
    )
  );

-- paquete_margenes: solo propietario
create policy "paquete_margenes: solo propietario"
  on public.paquete_margenes
  for all
  to authenticated
  using (
    exists (
      select 1 from public.usuarios_personal up
      where up.id = auth.uid() and up.rol = 'propietario'
    )
  );

-- Habilitar RLS en las tres tablas
alter table public.producto_costos enable row level security;
alter table public.producto_margenes enable row level security;
alter table public.paquete_margenes enable row level security;
