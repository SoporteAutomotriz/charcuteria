-- Migración 1: Esquema público base (Fase 2)
-- Tablas: usuarios_personal, categorias, productos, paquetes, paquete_componentes,
--         zonas_transporte, tarifas_montaje, perfiles_consumo, parametros_globales

-- 1. Usuarios del personal (Supabase Auth + rol propio)
create table if not exists public.usuarios_personal (
  id uuid references auth.users not null primary key,
  email text not null,
  rol text not null check (rol in ('propietario', 'administrador')),
  nombre text not null,
  activo boolean not null default true,
  creado_en timestamptz not null default now()
);

-- 2. Categorías del catálogo (sección 4)
create table if not exists public.categorias (
  id bigint generated by default as identity primary key,
  nombre text not null,
  orden_visualizacion int not null default 0,
  activo boolean not null default true,
  creado_en timestamptz not null default now()
);

-- 3. Productos del catálogo (sección 4)
-- costos y márgenes van en tablas privadas separadas (sección 11)
create table if not exists public.productos (
  id bigint generated by default as identity primary key,
  categoria_id bigint references public.categorias(id),
  nombre text not null,
  descripcion text,
  foto_url text,
  orden_visualizacion int not null default 0,
  unidad_compra text not null,
  unidad_venta text not null,
  factor_conversion numeric(10,4) not null default 1,
  merma_pct numeric(5,2) not null default 0,
  porcion_referencia_persona numeric(10,2),
  alergenos text[],
  etiquetas text[],
  estado text not null check (estado in ('activo', 'agotado_temporal', 'inactivo')) default 'activo',
  creado_en timestamptz not null default now(),
  actualizado_en timestamptz not null default now()
);

-- 4. Paquetes (sección 5)
create table if not exists public.paquetes (
  id bigint generated by default as identity primary key,
  nombre text not null,
  foto_url text,
  descripcion text,
  personas_recomendadas int not null default 1,
  creado_en timestamptz not null default now(),
  actualizado_en timestamptz not null default now()
);

-- 5. Componentes de paquetes (sección 5)
create table if not exists public.paquete_componentes (
  id bigint generated by default as identity primary key,
  paquete_id bigint references public.paquetes(id) on delete cascade,
  categoria_id bigint references public.categorias(id), -- para sustitución dentro de categoría
  nombre text not null,
  cantidad_referencia numeric(10,4) not null default 1,
  tipo text not null check (tipo in ('fijo', 'sustituible', 'opcional', 'quitable')) default 'fijo',
  creado_en timestamptz not null default now()
);

-- 6. Zonas de transporte (sección 7)
create table if not exists public.zonas_transporte (
  id bigint generated by default as identity primary key,
  nombre text not null,
  municipios text[] not null default '{}',
  tarifa_fija numeric(12,2) not null default 0,
  cargo_distancia numeric(12,2) not null default 0,
  cargo_horario numeric(12,2) not null default 0,
  cargo_acceso_dificil numeric(12,2) not null default 0,
  zona_especial boolean not null default false,
  activo boolean not null default true
);

-- 7. Tarifas de montaje y personal (sección 7)
create table if not exists public.tarifas_montaje (
  id bigint generated by default as identity primary key,
  tarifa_hora numeric(12,2) not null default 0,
  horas_minimas int not null default 0,
  regla_personal_por_invitados int not null default 0, -- N: 1 persona por cada N invitados
  activo boolean not null default true
);

-- 8. Perfiles de consumo (sección 7)
create table if not exists public.perfiles_consumo (
  id bigint generated by default as identity primary key,
  tipo_evento text not null,
  duracion_rango text,
  categoria text not null,
  gramos_por_persona numeric(10,2) not null default 0,
  es_comida_principal boolean not null default false,
  activo boolean not null default true
);

-- 9. Parámetros globales (solo propietario puede escribir)
create table if not exists public.parametros_globales (
  id bigint generated by default as identity primary key,
  clave text not null unique,
  valor jsonb not null default '{}',
  descripcion text,
  creado_en timestamptz not null default now(),
  actualizado_en timestamptz not null default now()
);

-- 10. Bitácora de auditoría (solo lectura para todos, escrita por triggers/servidor)
create table if not exists public.bitacora_auditoria (
  id bigint generated by default as identity primary key,
  tabla_afectada text not null,
  registro_id bigint not null,
  accion text not null check (accion in ('insert', 'update', 'delete')),
  valores_anteriores jsonb,
  valores_nuevos jsonb,
  usuario_id uuid,
  ip text,
  fecha timestamptz not null default now()
);

