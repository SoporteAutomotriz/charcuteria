-- POLÍTICAS RLS — Tablas públicas
-- ============================================================

-- Helper: solo propietario
create policy "usuarios_personal: solo propietario escribe"
  on public.usuarios_personal
  for all
  to authenticated
  using (
    exists (
      select 1 from public.usuarios_personal up
      where up.id = auth.uid() and up.rol = 'propietario'
    )
  );

-- Cada usuario puede leer su propia fila
create policy "usuarios_personal: leer propia fila"
  on public.usuarios_personal
  for select
  to authenticated
  using (auth.uid() = id);

