-- Migración 2: Cotizaciones, versiones y costos privados (Fase 2)
-- Tablas: cotizaciones (vigente), cotizacion_versiones (historial de solo lectura),
--         cotizacion_costos (privada, solo Propietario, en paralelo a cotizaciones)
-- No hay RLS para el rol anon en ninguna de estas tres tablas: el acceso
-- del público se hace por endpoint de servidor (service_role) y por token largo.
--
-- Modelo de versionado (opción b): cotizaciones guarda la versión vigente.
-- Cuando el estado llega a "enviada" por primera vez, se congela automáticamente
-- como numero_version 1 en cotizacion_versiones (ver trigger en migración 3).

-- 1. Tabla cotizaciones — versión vigente (la que el cliente ve por su enlace privado)
create table if not exists public.cotizaciones (
  id bigint generated by default as identity primary key,
  folio text not null unique check (folio ~ '^CS-\d{4}-\d{4}$'),
  datos_cliente jsonb not null default '{}',
  datos_evento jsonb not null default '{}',
  datos_productos jsonb not null default '{}',
  datos_paquetes jsonb not null default '{}',
  estado text not null check (
    estado in (
      'recibida', 'en_revision', 'enviada', 'aceptada',
      'confirmada', 'realizada', 'cancelada', 'vencida'
    )
  ) default 'recibida',
  vigencia_en timestamptz,
  token text not null unique,
  token_expires_en timestamptz not null,
  total_venta numeric(12,2) not null default 0,
  descuento_pct numeric(5,2) not null default 0 check (descuento_pct between 0 and 100),
  creado_en timestamptz not null default now(),
  actualizado_en timestamptz not null default now(),
  -- Columnas de consentimiento y aviso de privacidad (sección 10)
  fecha_aceptacion_privacidad timestamptz,
  version_aviso_privacidad text,
  canal_contacto_consentido text check (
    canal_contacto_consentido in ('correo', 'whatsapp', 'ambos')
  ),
  creado_por uuid references public.usuarios_personal(id)
);

-- 2. Tabla cotizaciones_costos — privada, solo Propietario, en paralelo a cotizaciones
-- Un registro de costos por cotización vigente.
create table if not exists public.cotizaciones_costos (
  id bigint generated by default as identity primary key,
  cotizacion_id bigint references public.cotizaciones(id) on delete cascade,
  total_costo numeric(12,2) not null default 0,
  datos_costo jsonb not null default '{}',
  creado_en timestamptz not null default now(),
  actualizado_en timestamptz not null default now(),
  unique (cotizacion_id)
);

-- 3. Tabla cotizacion_versiones — historial de solo lectura, una fila por versión
create table if not exists public.cotizacion_versiones (
  id bigint generated by default as identity primary key,
  cotizacion_id bigint references public.cotizaciones(id) on delete cascade,
  numero_version int not null,
  estado text not null,
  total_venta numeric(12,2) not null default 0,
  total_costo numeric(12,2) not null default 0,
  datos_cliente jsonb not null default '{}',
  datos_evento jsonb not null default '{}',
  datos_productos jsonb not null default '{}',
  datos_paquetes jsonb not null default '{}',
  datos_costo_congelados jsonb not null default '{}',
  token text not null,
  fecha_aceptacion_privacidad timestamptz,
  version_aviso_privacidad text,
  canal_contacto_consentido text,
  creado_por uuid references public.usuarios_personal(id),
  creado_en timestamptz not null default now(),
  unique (cotizacion_id, numero_version)
);

-- Índices para búsquedas frecuentes
create index if not exists idx_cotizaciones_token on public.cotizaciones(token);
create index if not exists idx_cotizaciones_estado on public.cotizaciones(estado);
create index if not exists idx_cotizaciones_creado_en on public.cotizaciones(creado_en);
create index if not exists idx_cotizacion_versiones_cotizacion on public.cotizacion_versiones(cotizacion_id);

-- ============================================================
-- POLÍTICAS RLS — Cotizaciones, versiones y costos
-- ============================================================

-- Helper: propietario o administrador (usuarios del personal autenticados)
-- Nota: no hay políticas para el rol `anon` en estas tablas.

-- cotizaciones: propietario y administrador leen/escriben todo (excepto costos, que están en tabla aparte)
create policy "cotizaciones: propietario y administrador"
  on public.cotizaciones
  for all
  to authenticated
  using (
    exists (
      select 1 from public.usuarios_personal up
      where up.id = auth.uid() and up.rol in ('propietario', 'administrador')
    )
  );

-- cotizaciones_costos: solo propietario
create policy "cotizaciones_costos: solo propietario"
  on public.cotizaciones_costos
  for all
  to authenticated
  using (
    exists (
      select 1 from public.usuarios_personal up
      where up.id = auth.uid() and up.rol = 'propietario'
    )
  );

-- cotizacion_versiones: solo lectura para propietario y administrador
-- (escrita por servidor con service_role y por trigger de congelado automático)
create policy "cotizacion_versiones: solo lectura propietario y administrador"
  on public.cotizacion_versiones
  for select
  to authenticated
  using (
    exists (
      select 1 from public.usuarios_personal up
      where up.id = auth.uid() and up.rol in ('propietario', 'administrador')
    )
  );

-- Habilitar RLS en las tres tablas
alter table public.cotizaciones enable row level security;
alter table public.cotizaciones_costos enable row level security;
alter table public.cotizacion_versiones enable row level security;
